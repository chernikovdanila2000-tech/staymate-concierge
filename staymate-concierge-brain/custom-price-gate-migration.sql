-- кабінет не мав звідки взяти його персональну ціну. Він бачив загальний
-- "оберіть тариф" екран із трьома фіксованими планами — міг випадково
-- оплатити не ту суму, яку йому назвав AI. Тепер ціна зберігається разом з
-- рядком properties одразу при створенні акаунта (cabinet/index.html,
-- obAiConfirmBtn), і кабінет завжди може повторно виставити рахунок саме на
-- неї, поки не прийде оплата.
-- Безпечно виконувати повторно. Виконати один раз у Supabase → SQL Editor → Run.

